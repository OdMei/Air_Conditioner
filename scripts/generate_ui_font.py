"""Generate the UI's LVGL 9 font subset from the Noto font already in this repo.

Requires Pillow, available in the existing Codex Python runtime. No downloads.
Only string literals used by app_ui*.c plus printable ASCII are included.
"""
from pathlib import Path
import ast
import hashlib
import re
import struct
import sys
from PIL import ImageFont

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "Project/Project/Air_Conditioner/Appli/Core"
SOURCE = ROOT / "Middlewares/LVGL/tests/src/test_files/fonts/noto/NotoSansSC-Regular.ttf"
OUTPUT = CORE / "Src/app_font_ui_16.c"


def has_glyph(data, codepoint):
    """Read Unicode cmap formats 12/4 to reject missing-glyph rasterization."""
    u16 = lambda offset: struct.unpack_from(">H", data, offset)[0]
    u32 = lambda offset: struct.unpack_from(">I", data, offset)[0]
    tables = u16(4)
    cmap = next(u32(12 + index * 16 + 8) for index in range(tables)
                if data[12 + index * 16:16 + index * 16] == b"cmap")
    offsets = [cmap + u32(cmap + 4 + index * 8 + 4)
               for index in range(u16(cmap + 2))]
    for offset in offsets:
        if u16(offset) == 12:
            for index in range(u32(offset + 12)):
                start, end, glyph = struct.unpack_from(">III", data, offset + 16 + index * 12)
                if start <= codepoint <= end:
                    return glyph + codepoint - start != 0
        elif u16(offset) == 4 and codepoint <= 0xFFFF:
            count = u16(offset + 6) // 2
            ends = offset + 14
            starts = ends + count * 2 + 2
            deltas = starts + count * 2
            ranges = deltas + count * 2
            for index in range(count):
                start, end = u16(starts + index * 2), u16(ends + index * 2)
                if start <= codepoint <= end:
                    delta = u16(deltas + index * 2)
                    distance = u16(ranges + index * 2)
                    if distance == 0:
                        return ((codepoint + delta) & 0xFFFF) != 0
                    glyph = u16(ranges + index * 2 + distance + (codepoint - start) * 2)
                    return glyph != 0 and ((glyph + delta) & 0xFFFF) != 0
    return False


def main():
    ui = "\n".join(path.read_text(encoding="utf-8-sig")
                   for path in sorted((CORE / "Src").glob("app_ui*.c")))
    characters = set(chr(value) for value in range(32, 127))
    for literal in re.findall(r'"(?:[^"\\]|\\.)*"', ui):
        characters.update(character for character in ast.literal_eval(literal)
                          if ord(character) >= 32)
    characters = sorted(characters, key=ord)
    source_bytes = SOURCE.read_bytes()
    missing = [character for character in characters if not has_glyph(source_bytes, ord(character))]
    if missing:
        raise RuntimeError("Missing source glyphs: " + "".join(missing))
    font = ImageFont.truetype(str(SOURCE), 16, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    descriptors = ["    {0, 0, 0, 0, 0, 0}, /* Reserved missing glyph. */"]
    for character in characters:
        mask, (left, top) = font.getmask2(character, mode="L", anchor="ls")
        width, height = mask.size
        bitmap_index = len(bitmap)
        pixels = bytes(mask)
        # LVGL's plain 4bpp format packs pixels continuously, including across rows.
        for index in range(0, len(pixels), 2):
            bitmap.append((pixels[index] & 0xF0) |
                          ((pixels[index + 1] >> 4) if index + 1 < len(pixels) else 0))
        advance = round(font.getlength(character) * 16)
        descriptors.append(f"    {{{bitmap_index}, {advance}, {width}, {height}, {left}, {-top - height}}}, /* U+{ord(character):04X} */")
    start = ord(characters[0])
    offsets = [ord(character) - start for character in characters]
    if offsets[-1] >= 65535:
        raise RuntimeError("This subset requires more than one LVGL cmap")
    rows = ["    " + ", ".join(f"0x{value:02X}" for value in bitmap[index:index + 16]) + ","
            for index in range(0, len(bitmap), 16)]
    unicode_rows = ["    " + ", ".join(f"0x{value:04X}" for value in offsets[index:index + 12]) + ","
                    for index in range(0, len(offsets), 12)]
    output = f'''/* Generated by scripts/generate_ui_font.py; do not edit bitmap data.
 * Derived subset: AC UI 16. Source Noto Sans SC Regular (SIL OFL 1.1).
 * Copyright 2014-2021 Adobe, with Reserved Font Name 'Source'.
 * License/provenance: docs/fonts/OFL-NotoSansSC.txt and docs/fonts/README.md.
 * Source SHA-256: {hashlib.sha256(source_bytes).hexdigest()}
 * {len(characters)} glyphs, 16px, plain 4bpp, {len(bitmap)} bitmap bytes, no kerning.
 */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
{chr(10).join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptors)}
}};

static const uint16_t unicode_list[] = {{
{chr(10).join(unicode_rows)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = {start}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1,
        .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,
        .list_length = {len(characters)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = LV_FONT_FMT_TXT_PLAIN
}};

const lv_font_t app_font_ui_16 = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent}, .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1,
    .dsc = &font_dsc
}};
'''
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            raise RuntimeError("Generated font is stale; rerun scripts/generate_ui_font.py")
        print(f"Font is current; all {len(characters)} glyphs have source cmap coverage")
        return
    OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    license_source = SOURCE.parent / "OFL.txt"
    license_output = ROOT / "docs/fonts/OFL-NotoSansSC.txt"
    license_output.parent.mkdir(parents=True, exist_ok=True)
    license_output.write_bytes(license_source.read_bytes())
    print(f"Generated {OUTPUT}: {len(characters)} glyphs, {len(bitmap)} bitmap bytes, line height {ascent + descent}")
    print("Chinese/symbol charset:", "".join(character for character in characters if ord(character) > 126))


if __name__ == "__main__":
    main()
